/** Interaction regression using synthetic data; failed writes are intercepted locally. */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const { chromium } = createRequire(import.meta.url)(process.env.TRADE_CRM_PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.TRADE_CRM_REVIEW_ORIGIN || 'http://127.0.0.1:8794';
assert.match(origin, /^http:\/\/127\.0\.0\.1:\d+$/);
const token = process.env.TRADE_CRM_REVIEW_TOKEN;
assert.ok(token?.length >= 32);
const output = process.env.TRADE_CRM_REVIEW_OUTPUT || join(tmpdir(), 'trade-crm-ui-interactions');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.TRADE_CRM_CHROME_BINARY, headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, extraHTTPHeaders: { 'X-CRM-Review-Token': token }, serviceWorkers: 'block', locale: 'fa-IR' });
const page = await context.newPage();
const results = [];
const check = (condition, message) => { assert.ok(condition, message); results.push(message); console.log('PASS ' + message); };
try {
  const before = await (await context.request.get(origin + '/_crm_review_fingerprint')).json();
  await page.goto(origin + '/crm/?view=profile&contact=1', { waitUntil: 'networkidle' });
  await page.locator('.profile-card').waitFor();
  await page.locator('.profile-info summary').click();
  check(await page.locator('.profile-info').getAttribute('open') !== null, 'full profile information is accessible on mobile');
  const open = page.getByRole('button', { name: 'ثبت نتیجه پیگیری', exact: true });
  await open.click();
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  const finalAction = dialog.locator('button:not(:disabled)').last();
  await finalAction.focus();
  await page.keyboard.press('Tab');
  check(await dialog.evaluate((e) => e.contains(document.activeElement)), 'Tab cycles inside the modal');
  await dialog.getByLabel('نتیجه گفت‌وگو *', { exact: true }).fill('نتیجهٔ آزمایشی حفظ‌شده پس از خطا');
  await page.route('**/contacts/1/followup/complete', (route) => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ code: 'trade_crm_ui_test_error', message: 'خطای آزمایشی برای بررسی پنجره' }) }));
  await dialog.getByRole('button', { name: 'ثبت نتیجه', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  await writeFile(join(output, 'modal-error.html'), await page.content());
  await page.screenshot({ path: join(output, 'modal-error.png') });
  check((await dialog.getByRole('alert').innerText()).includes('خطای آزمایشی'), 'follow-up errors are shown inside the modal');
  check(await dialog.getByLabel('نتیجه گفت‌وگو *', { exact: true }).inputValue() === 'نتیجهٔ آزمایشی حفظ‌شده پس از خطا', 'a failed follow-up preserves its draft');
  check(await dialog.getByRole('button', { name: 'ثبت نتیجه', exact: true }).isEnabled(), 'retry becomes available after the error');
  await dialog.getByLabel('نتیجه گفت‌وگو *', { exact: true }).focus();
  await page.setViewportSize({ width: 390, height: 400 });
  await page.waitForFunction(() => document.documentElement.classList.contains('crm-keyboard-open'));
  check(await page.locator('.mobile-nav').evaluate((e) => getComputedStyle(e).display === 'none'), 'reduced editing viewport hides bottom navigation');
  check(await dialog.evaluate((e) => { const r = e.getBoundingClientRect(); return r.top >= 0 && r.bottom <= innerHeight + 1; }), 'modal fits inside the reduced editing viewport');
  await page.screenshot({ path: join(output, 'modal-reduced-viewport.png') });
  await page.keyboard.press('Escape');
  check(await dialog.count() === 0, 'Escape closes the follow-up modal');
  check(await open.evaluate((e) => e === document.activeElement), 'modal dismissal restores the trigger focus');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => !document.documentElement.classList.contains('crm-keyboard-open'));
  const menu = page.getByRole('button', { name: 'بازکردن منو', exact: true });
  await menu.click();
  check(await page.locator('#crm-navigation').evaluate((e) => e.contains(document.activeElement)), 'mobile drawer receives focus');
  check(await page.locator('.main-area').evaluate((e) => e.inert), 'drawer background is inert');
  await page.keyboard.press('Escape');
  check(await menu.evaluate((e) => e === document.activeElement), 'drawer dismissal restores focus');
  check(await page.locator('.main-area').evaluate((e) => !e.inert), 'drawer dismissal restores the page');
  await page.goto(origin + '/crm/?view=form', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'ثبت مخاطب', exact: true }).click();
  check(await page.getByLabel('نام *', { exact: true }).evaluate((e) => e === document.activeElement), 'required validation focuses the first name field');
  await page.setViewportSize({ width: 390, height: 400 });
  await page.waitForFunction(() => document.documentElement.classList.contains('crm-keyboard-open'));
  check(await page.locator('.contact-form-actions').evaluate((e) => getComputedStyle(e).position === 'static'), 'save actions stop sticking in the reduced editing viewport');
  const after = await (await context.request.get(origin + '/_crm_review_fingerprint')).json();
  check(JSON.stringify(after) === JSON.stringify(before), 'interaction checks do not change the synthetic database');
} finally {
  await browser.close();
  await writeFile(join(output, 'interaction-results.json'), JSON.stringify({ results, note: 'Chrome reduced viewport simulates keyboard geometry; no physical iPhone keyboard was tested.' }, null, 2));
}
